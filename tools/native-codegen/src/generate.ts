import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import {
  AuthMethod,
  MfaChallengePurpose,
  MfaFactorType,
  SessionRevokeReason,
} from "@idenzy/protocol/enums/auth";
import { Channel } from "@idenzy/protocol/enums/delivery";
import { ErrorCode } from "@idenzy/protocol/errors/codes";
import { IdenzyHeader, SessionTransport } from "@idenzy/protocol/http/headers";
import { ApiKeyPrefix } from "@idenzy/protocol/schemas/common";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const native = join(root, "packages", "sdk", "native");

/** A protocol enum, and what its Rust doc comment says about it. */
interface WireEnum {
  readonly name: string;
  readonly doc: string;
  readonly values: Readonly<Record<string, string>>;
}

/**
 * The enums a native client reads off the wire.
 *
 * Only the ones a response carries. Every one gains an `Unrecognized` variant, because a
 * mobile binary outlives the API it was built against: a code or a factor added after the
 * build has to arrive as something a customer's `switch` can fall through, not as a parse
 * failure that turns a known refusal into a transport error (ADR-0022).
 */
const ENUMS: readonly WireEnum[] = [
  {
    name: "ErrorCode",
    doc: "Every code the API answers an error with. Branch on this, never on the message.",
    values: ErrorCode,
  },
  {
    name: "MfaFactorType",
    doc: "A kind of second factor, as a challenge offers it and a factor list reports it.",
    values: MfaFactorType,
  },
  {
    name: "MfaChallengePurpose",
    doc: "Whether a challenge finishes a sign-in or raises an existing session's assurance.",
    values: MfaChallengePurpose,
  },
  {
    name: "AuthMethod",
    doc: "How a session was authenticated, as its `amr` claim and the device list name it.",
    values: AuthMethod,
  },
  {
    name: "SessionRevokeReason",
    doc: "Why a session in the device list ended.",
    values: SessionRevokeReason,
  },
];

/** String constants the core sends, grouped the way the protocol groups them. */
const CONSTANTS: readonly { readonly module: string; readonly values: Record<string, string> }[] = [
  { module: "header", values: IdenzyHeader },
  { module: "session_transport", values: SessionTransport },
  { module: "api_key_prefix", values: ApiKeyPrefix },
  { module: "channel", values: Channel },
];

const PREAMBLE = `// @generated by tools/native-codegen from @idenzy/protocol. Do not edit by hand.
//
// Run \`pnpm native:generate\` after changing the protocol. CI runs \`pnpm native:check\`, which
// fails when this file and the protocol disagree, the same contract as the compliance artifacts.
`;

function renderEnum({ name, doc, values }: WireEnum): string {
  const entries = Object.entries(values);
  const variants = entries.map(([variant]) => `    ${variant},`).join("\n");
  const fromWire = entries
    .map(([variant, wire]) => `            ${JSON.stringify(wire)} => Self::${variant},`)
    .join("\n");
  const asWire = entries
    .map(([variant, wire]) => `            Self::${variant} => Some(${JSON.stringify(wire)}),`)
    .join("\n");
  return `/// ${doc}
///
/// \`Unrecognized\` is a value newer than this build. The raw string is kept wherever one of
/// these is reported, so a newer value is visible rather than lost.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, uniffi::Enum)]
pub enum ${name} {
${variants}
    Unrecognized,
}

impl ${name} {
    pub(crate) fn from_wire(value: &str) -> Self {
        match value {
${fromWire}
            _ => Self::Unrecognized,
        }
    }

    pub(crate) fn as_wire(self) -> Option<&'static str> {
        match self {
${asWire}
            Self::Unrecognized => None,
        }
    }
}

impl<'de> serde::Deserialize<'de> for ${name} {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let value = String::deserialize(deserializer)?;
        Ok(Self::from_wire(&value))
    }
}

/// The wire value, for a platform layer that hands it on: a Flutter or React Native bridge
/// passes strings, and reading them from here means it never keeps a table of its own.
#[uniffi::export]
pub fn wire_${snake(name)}(value: ${name}) -> Option<String> {
    value.as_wire().map(str::to_owned)
}
`;
}

function snake(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
}

function renderConstants(module: string, values: Record<string, string>): string {
  const lines = Object.entries(values)
    .map(([key, value]) => `    pub const ${screamingSnake(key)}: &str = ${JSON.stringify(value)};`)
    .join("\n");
  return `pub(crate) mod ${module} {\n${lines}\n}\n`;
}

function screamingSnake(key: string): string {
  return key.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
}

function renderRust(): string {
  const parts = [
    PREAMBLE,
    ...ENUMS.map(renderEnum),
    ...CONSTANTS.map(({ module, values }) => renderConstants(module, values)),
  ];
  return parts.join("\n");
}

/**
 * The same enums for Dart, so a Flutter app branches on the codes the API defines rather than on
 * strings the plugin copied once. The native SDKs hand the plugin wire values, and these turn
 * them back into names, with `unrecognized` for a value newer than the build.
 */
function renderDartEnum({ name, doc, values }: WireEnum): string {
  const members = Object.entries(values)
    .map(([variant, wire]) => `  ${lowerCamel(variant)}(${JSON.stringify(wire)}),`)
    .join("\n");
  return `/// ${doc}
///
/// [unrecognized] is a value newer than this build. The raw string is kept wherever one of these
/// is reported, so a newer value is visible rather than lost.
enum ${name} {
${members}
  unrecognized(null);

  const ${name}(this.wire);

  /// What the API sends, or null for [unrecognized].
  final String? wire;

  static ${name} fromWire(String? value) => values.firstWhere(
        (member) => value != null && member.wire == value,
        orElse: () => ${name}.unrecognized,
      );
}
`;
}

function renderDart(): string {
  return [PREAMBLE, ...ENUMS.map(renderDartEnum)].join("\n");
}

function lowerCamel(key: string): string {
  return key.charAt(0).toLowerCase() + key.slice(1);
}

/** Every file generated from the protocol, and what writes it. */
const TARGETS: readonly { readonly path: string; readonly render: () => string }[] = [
  { path: join(native, "core", "src", "protocol", "generated.rs"), render: renderRust },
  {
    path: join(native, "flutter", "idenzy_flutter", "lib", "src", "generated", "protocol.dart"),
    render: renderDart,
  },
];

/**
 * Regenerates the native core's and the Flutter plugin's copies of the protocol enums.
 *
 * With --check it verifies the committed file instead of writing it, which is how CI fails a
 * protocol change that would otherwise reach every mobile SDK as a silent divergence.
 */
async function main(): Promise<void> {
  const checkOnly = process.argv.includes("--check");
  const reserved = ENUMS.filter(({ values }) => Object.hasOwn(values, "Unrecognized"));
  if (reserved.length > 0) {
    process.stderr.write(
      `${reserved.map(({ name }) => name).join(", ")} declares Unrecognized, which the native ` +
        "core reserves for values newer than the build. Rename the protocol member.\n",
    );
    process.exit(1);
  }
  const stale: string[] = [];
  for (const { path, render } of TARGETS) {
    const generated = render();
    const shown = relative(root, path);
    if (checkOnly) {
      const existing = await readFile(path, "utf8").catch(() => "");
      if (existing !== generated) stale.push(shown);
      continue;
    }
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, generated, "utf8");
    process.stdout.write(`wrote ${shown}\n`);
  }
  if (stale.length > 0) {
    process.stderr.write(
      `Stale: ${stale.join(", ")}.\nRun \`pnpm native:generate\` and commit the result.\n`,
    );
    process.exit(1);
  }
  if (checkOnly) process.stdout.write("native protocol enums are current\n");
}

await main();
